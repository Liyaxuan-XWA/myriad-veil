def sheet_frames(anim: str) -> int:
    """单张姿势表里放几个姿势 —— 实测模型最多稳定放 3~4 个，再多就粘连。"""
    return 4 if anim == "walk_side" else 3


def total_frames(anim: str) -> int:
    """该动作总帧数 = 两张表之和（idle 6 / walk 8 / 招式 6）。"""
    return sheet_frames(anim) * 2


def frame_count(anim: str) -> int:
    """该动作的总帧数。

    旧值：idle / walk 4、招式 3 —— 太稀，播起来是"跳"不是"动"。
    新值：idle 6、walk_side 8、招式 6。

    ⚠ 与 tools/gen_boss_sprite_frames.py split --frames 必须一致。帧数写多了会把一只虎劈成两半，
      写少了会两帧并进一格 —— 两边都以本函数为准，改这里就要改命令行。
    ⚠ 1536 宽的图放 8 个姿势=192px/只，听着小，但游戏里最终只显示约 140px 高，
      源分辨率仍然大于显示尺寸，不会糊。
    """
    return total_frames(anim)


def build_prompt(boss_id: str, anim: str, part: int = 1) -> str:
    """拼装顺序固定：BG → STYLE → ANCHOR → POSE → NEG → LAYOUT。

    part=1 取 POSES（起手半程），part=2 取 POSES_B（收势半程）；没写 POSES_B 的动作只能 part=1。

    ⚠ 背景必须排第一：模型对靠前的约束服从度明显更高，放末尾会被风格词带跑（实测）。
    ⚠ 负面清单必须紧跟在动作之后、构图之前 —— 放在最末会被忽略。
    ⚠ 改顺序或增删段落都会让历史素材与新素材产生风格漂移，别随手动。
    """
    anchor = ANCHOR.get(boss_id)
    pose = POSES.get(boss_id, {}).get(anim)
    if anchor is None:
        raise KeyError(f"未登记 BOSS：{boss_id}（可选：{', '.join(ANCHOR)}）")
    if pose is None:
        raise KeyError(f"{boss_id} 未登记动作：{anim}（可选：{', '.join(POSES[boss_id])}）")
    if part == 2:
        second = POSES_B.get(boss_id, {}).get(anim)
        if second is None:
            raise KeyError(f"{boss_id}/{anim} 没有登记后半程（POSES_B）")
        pose = second
    neg = NEG.get(boss_id, "")
    count = sheet_frames(anim)
    tag = f"第{part}张（共2张）" if part in (1, 2) and POSES_B.get(boss_id, {}).get(anim) else ""
    style = STYLE_CEL if boss_id in CEL_BOSSES else STYLE
    return f"{BG}{style}{anchor}动作：{tag}{pose}。横向并排{count}个姿势。{neg}{LAYOUT}"


def build_rig_prompt(boss_id: str) -> str:
    """骨肯定妆图提示词（单姿势全身像）。拼装顺序与姿势表一致：BG → STYLE → ANCHOR → POSE → NEG → 构图。"""
    anchor = ANCHOR.get(boss_id)
    pose = RIG_POSE.get(boss_id)
    if anchor is None:
        raise KeyError(f"未登记 BOSS：{boss_id}（可选：{', '.join(ANCHOR)}）")
    if pose is None:
        raise KeyError(f"{boss_id} 还没登记骨骼定妆姿势（RIG_POSE）")
    neg = NEG.get(boss_id, "")
    style = STYLE_CEL if boss_id in CEL_BOSSES else STYLE
    return f"{BG}{style}{anchor}姿势：{pose}。{neg}{RIG_LAYOUT}"


def main() -> int:
    ap = argparse.ArgumentParser(description="打印 BOSS 美术提示词（拼装顺序固定，勿手改）")
    ap.add_argument("boss", nargs="?", help="BOSS id，如 boss_huyao")
    ap.add_argument("anim", nargs="?", help="动作名，如 idle / slash_single")
    ap.add_argument("--part", type=int, default=1, choices=[1, 2], help="1=起手半程 2=收势半程")
    ap.add_argument("--list", action="store_true", help="列出全部 BOSS 与动作")
    args = ap.parse_args()

    if args.list or not args.boss:
        for bid, poses in POSES.items():
            items = ", ".join(f"{a}({frame_count(a)}帧/{sheet_frames(a)}+{sheet_frames(a)})" for a in poses)
            print(f"{bid}（{len(poses)} 套）：{items}")
        return 0

    if args.anim:
        print(build_prompt(args.boss, args.anim, args.part))
        return 0

    for anim in POSES.get(args.boss, {}):
        print(f"\n===== {args.boss} / {anim} =====")
        print(build_prompt(args.boss, anim, 1))
        if POSES_B.get(args.boss, {}).get(anim):
            print(f"----- {args.boss} / {anim} 后半程 -----")
            print(build_prompt(args.boss, anim, 2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
